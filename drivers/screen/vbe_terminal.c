void kputchar(uint8_t ch, uint8_t attr) {
    draw_cursor(0);
    if (ch == '\n') {
        cursor_x = 0;
        cursor_y++;
    } else if (ch == '\b') {
        if (cursor_x > 0) cursor_x--;
        for (int r = 0; r < FONT_HEIGHT; r++) {
            for (int c = 0; c < FONT_WIDTH; c++) {
                draw_pixel(backbuf, cursor_x * FONT_WIDTH + c, cursor_y * FONT_HEIGHT + r, background_color);
            }
        }
    } else {
        uint8_t fg = attr & 0x0F;
        uint8_t bg = (attr >> 4) & 0x0F;
        for (int r = 0; r < FONT_HEIGHT; r++) {
            uint8_t bits = font8x16[ch][r];
            for (int c = 0; c < FONT_WIDTH; c++) {
                uint8_t color = (bits & (1 << (7 - c))) ? fg : bg;
                draw_pixel(backbuf, cursor_x * FONT_WIDTH + c, cursor_y * FONT_HEIGHT + r, color);
            }
        }
        cursor_x++;
        if (cursor_x >= width / FONT_WIDTH) {
            cursor_x = 0;
            cursor_y++;
        }
    }
    if (cursor_y >= height / FONT_HEIGHT) {
        uint32_t line_bytes = FONT_HEIGHT * width;
        memmove(backbuf, backbuf + line_bytes, (height * width - line_bytes));
        memset(backbuf + (height * width - line_bytes), background_color, line_bytes);
        cursor_y = height / FONT_HEIGHT - 1;
    }
    draw_cursor(cursor_blink);
    //vbe_swap();
}

void kprint(uint8_t *str) {
    while (*str) {
        kputchar(*str++, 0x0F);
    }
}

// Parse color tags <(BG FG)>
static uint8_t parse_color_code(char bg, char fg) {
    uint8_t background = 0, foreground = 0;
    if (bg >= '0' && bg <= '9') background = bg - '0';
    else if (bg >= 'a' && bg <= 'f') background = bg - 'a' + 0xa;
    else if (bg >= 'A' && bg <= 'F') background = bg - 'A' + 0xa;
    if (fg >= '0' && fg <= '9') foreground = fg - '0';
    else if (fg >= 'a' && fg <= 'f') foreground = fg - 'a' + 0xa;
    else if (fg >= 'A' && fg <= 'F') foreground = fg - 'A' + 0xa;
    return (background << 4) | foreground;
}

// Convert integer to hex string (uppercase)
static void hex_to_str(uint32_t num, char *str) {
    int i = 0;
    if (num == 0) { str[i++] = '0'; str[i] = '\0'; return; }
    while (num) {
        uint32_t rem = num % 16;
        str[i++] = (rem < 10) ? '0' + rem : 'A' + (rem - 10);
        num /= 16;
    }
    str[i] = '\0';
    // reverse
    int start = 0, end = i - 1;
    while (start < end) { char tmp = str[start]; str[start] = str[end]; str[end] = tmp; start++; end--; }
}

// Float to string with given precision
static void ftos(double n, char *buf, int precision) {
    int i = 0, sign = 1;
    if (n < 0) { sign = -1; n = -n; }
    double ip = (int)n;
    double fp = n - ip;
    if (ip == 0) buf[i++] = '0';
    while (ip > 0) { buf[i++] = ((int)ip % 10) + '0'; ip /= 10; }
    if (sign < 0) buf[i++] = '-';
    // reverse integer part
    int j = 0, k = i - 1;
    while (j < k) { char t = buf[j]; buf[j++] = buf[k]; buf[k--] = t; }
    buf[i++] = '.';
    for (int p = 0; p < precision; p++) {
        fp *= 10;
        buf[i++] = (int)fp + '0';
        fp -= (int)fp;
    }
    buf[i] = '\0';
}

// Formatted print with %d, %u, %x, %X, %c, %s, %f and color tags
void kprintf(const char* format, ...) {
    char c;
    uint8_t current_color = 0x0F;
    char **arg = (char**)&format;
    int *int_arg;
    char *str_arg;
    char num_buf[32];
    unsigned int uint_arg;
    double double_arg;
    arg++; // first arg
    while ((c = *format++) != 0) {
        if (c == '<' && *format == '(') {
            const char *f = format + 1;
            if (strncmp(format, "(endl)>", 7) == 0) {
                kputchar('\n', current_color);
                format += 7; // skip "(endl)>"
                continue;
            } else if (format[1] && format[2] && format[3] && format[4] && format[5]) {
                char bg = format[1];
                char fg = format[2];
                if (format[3] == ')' && format[4] == '>') {
                    current_color = parse_color_code(bg, fg);
                    format += 5; // skip "(BGFG)>"
                    continue;
                }
            }
            // not a tag, print as text
            kputchar('<', current_color);
            kputchar('(', current_color);
            format += 1; // move past '('
            continue;
        }
        if (c != '%') {
            kputchar(c, current_color);
            continue;
        }
        c = *format++;
        int width = 0, precision = -1;
        // width
        while (c >= '0' && c <= '9') { width = width*10 + (c - '0'); c = *format++; }
        // precision
        if (c == '.') {
            c = *format++;
            precision = 0;
            while (c >= '0' && c <= '9') { precision = precision*10 + (c - '0'); c = *format++; }
        }
        switch (c) {
            case 'd':
                int_arg = (int*)arg++;
                itoa(*int_arg, num_buf, 10);
                for (char *p = num_buf; *p; p++) kputchar(*p, current_color);
                break;
            case 'u':
                uint_arg = *(unsigned int*)arg++;
                itoa(uint_arg, num_buf, 10);
                for (char *p = num_buf; *p; p++) kputchar(*p, current_color);
                break;
            case 'x':
                uint_arg = *(unsigned int*)arg++;
                hex_to_str(uint_arg, num_buf);
                for (int i = 0; i < width - (int)strlen(num_buf); i++) kputchar('0', current_color);
                for (char *p = num_buf; *p; p++) kputchar(*p, current_color);
                break;
            case 'X':
                uint_arg = *(unsigned int*)arg++;
                hex_to_str(uint_arg, num_buf);
                for (int i = 0; i < width - (int)strlen(num_buf); i++) kputchar('0', current_color);
                for (char *p = num_buf; *p; p++) kputchar(*p, current_color);
                break;
            case 'c':
                int_arg = (int*)arg++;
                kputchar((char)*int_arg, current_color);
                break;
            case 's':
                str_arg = *(char**)arg++;
                {
                    int len = strlen(str_arg);
                    int to_print = precision >= 0 && precision < len ? precision : len;
                    for (int i = 0; i < to_print; i++) kputchar(str_arg[i], current_color);
                }
                break;
            case 'f':
                double_arg = *(double*)arg++;
                ftos(double_arg, num_buf, precision >= 0 ? precision : 2);
                for (char *p = num_buf; *p; p++) kputchar(*p, current_color);
                break;
            default:
                kputchar(c, current_color);
                break;
        }
    }
}

