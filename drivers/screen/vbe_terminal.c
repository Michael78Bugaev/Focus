void draw_pixel(uint8_t *buf, uint32_t x, uint32_t y, uint8_t color) {
    if (x < width && y < height) {
        buf[y * width + x] = color;
    }
}

void vbe_swap(void) {
    for (uint32_t y = 0; y < height; y++) {
        memcpy(backbuf + y * width, (uint8_t*)fb + y * pitch, width);
    }
}

void vbe_init(struct multiboot_info *mbi) {
    fb = (uint8_t*)(uintptr_t)mbi->framebuffer_addr;
    pitch = mbi->framebuffer_pitch;
    width = mbi->framebuffer_width;
    height = mbi->framebuffer_height;
    bpp = mbi->framebuffer_bpp;
    qemu_debug_printf("before malloc\n");
    backbuf = malloc(width * height);
    if (!backbuf) {
        qemu_debug_printf("Error allocating memory for backbuf\n");
        return;
    }
    qemu_debug_printf("after malloc\n");
    cursor_x = cursor_y = 0;
    memset(backbuf, 0, width * height);

    qemu_debug_printf("VBE initialized\n");
}

