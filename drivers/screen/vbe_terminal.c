void draw_cursor(int blink) {
    int x = cursor_x, y = cursor_y;
    if (blink) {
        if (!_cursor_drawn) {
            // save background under cursor
            for (int r = 0; r < FONT_HEIGHT; r++) {
                for (int c = 0; c < FONT_WIDTH; c++) {
                    _cursor_saved[r * FONT_WIDTH + c] =
                        backbuf[(y * FONT_HEIGHT + r) * width + (x * FONT_WIDTH + c)];
                }
            }
            _cursor_prev_x = x;
            _cursor_prev_y = y;
            // draw underline cursor like _ 
            for (int c = 0; c < FONT_WIDTH; c++) {
                draw_pixel(backbuf, x * FONT_WIDTH + c, y * FONT_HEIGHT + FONT_HEIGHT - 1, 0x0F);
            }
            // second layer of cursor
            for (int c = 0; c < FONT_WIDTH; c++) {
                draw_pixel(backbuf, x * FONT_WIDTH + c, y * FONT_HEIGHT + FONT_HEIGHT - 2, 0x0F);
            }
            _cursor_drawn = 1;
        }
    } else {
        if (_cursor_drawn) {
            // restore underline cursor
            for (int c = 0; c < FONT_WIDTH; c++) {
                draw_pixel(backbuf, x * FONT_WIDTH + c, y * FONT_HEIGHT + FONT_HEIGHT - 1, 0x00);
            }
            for (int c = 0; c < FONT_WIDTH; c++) {
                draw_pixel(backbuf, x * FONT_WIDTH + c, y * FONT_HEIGHT + FONT_HEIGHT - 2, 0x00);
            }
            _cursor_drawn = 0;
        }
    }
}

// Print 16-color BMP image at specified pixel offset x,y
void print_bmp16(uint8_t* bmp_data, uint32_t width, uint32_t height, uint32_t x, uint32_t y) {
    // Read pixel data offset from BMP header
    uint32_t data_offset = bmp_data[10] | (bmp_data[11] << 8) | (bmp_data[12] << 16) | (bmp_data[13] << 24);
    uint8_t* pixel_data = bmp_data + data_offset;

    // Calculate bytes per row (4bpp: two pixels per byte) and padding to 4-byte boundary
    uint32_t row_bytes = (width + 1) / 2;
    uint32_t padding = (4 - (row_bytes % 4)) % 4;
    row_bytes += padding;

    // Iterate rows top-to-bottom
    for (uint32_t row = 0; row < height; row++) {
        uint32_t src_row = height - 1 - row;
        uint8_t* row_ptr = pixel_data + src_row * row_bytes;
        for (uint32_t col = 0; col < width; col++) {
            uint8_t byte = row_ptr[col / 2];
            draw_pixel(backbuf, x + col, y + row, (col & 1) ? (byte & 0x0F) : (byte >> 4));
        }
    }
}
